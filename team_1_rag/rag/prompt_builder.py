
def build_prompt(query, context):
    """Формирует запрос для языковой модели."""

    prompt = f"""
Ты помощник учебного центра «Вектор».

Отвечай на вопрос пользователя, используя только информацию из контекста.

Если в контексте нет ответа, сообщи:
«В базе знаний нет подтверждённой информации».

Не придумывай факты и не используй внешние знания.

Контекст:
{context}

Вопрос:
{query}

Ответ:
"""
    return prompt.strip()
